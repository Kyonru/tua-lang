#!/usr/bin/env python3
"""Generate pinned Unicode 15.1 tables; input downloads are explicit, never implicit."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def records(text):
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        parts = [part.strip() for part in body.split(";")]
        bounds = parts[0].split("..")
        yield int(bounds[0], 16), int(bounds[-1], 16), parts[1:]


def merge(rows):
    result = []
    for start, end, value in sorted(rows):
        if result and result[-1][1] + 1 == start and result[-1][2] == value:
            result[-1] = (result[-1][0], end, value)
        else:
            result.append((start, end, value))
    return result


def generate(inputs):
    tables = {}
    tables["gcb"] = [(a, b, values[0]) for a, b, values in records(inputs["GraphemeBreakProperty.txt"])
                     if values[0] not in {"LV", "LVT"}]
    tables["pictographic"] = [(a, b, "yes") for a, b, values in records(inputs["emoji-data.txt"])
                              if values[0] == "Extended_Pictographic"]
    tables["indic"] = [(a, b, values[1]) for a, b, values in records(inputs["DerivedCoreProperties.txt"])
                       if values[0] == "InCB"]
    speech = []
    start = None
    for line in inputs["UnicodeData.txt"].splitlines():
        fields = line.split(";")
        code, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            start = code
        elif name.endswith(", Last>"):
            if category[0] in "LN":
                speech.append((start, code, "yes"))
            start = None
        elif category[0] in "LN":
            speech.append((code, code, "yes"))
    tables["speech"] = speech
    lines = ["-- Generated by scripts/generate-dialogue-unicode.py; do not hand-edit.",
             "-- Unicode 15.1 data copyright Unicode, Inc.; see tuadialogue_unicode.LICENSE.",
             "return {", '  version = "15.1.0",']
    for name, rows in tables.items():
        lines.append(f"  {name} = {{")
        for start, end, value in merge(rows):
            lines.append(f'    {{ {start}, {end}, "{value}" }},')
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path, help="directory of files named in unicode-15.1-manifest.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "scripts/unicode-15.1-manifest.json").read_text())
    inputs = {}
    for name, item in manifest.items():
        data = (args.data / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != item["sha256"]:
            raise SystemExit(f"Unicode checksum mismatch: {name}")
        inputs[name] = data.decode("utf-8")
    expected = generate(inputs)
    target = ROOT / "vendor/runtime/tuadialogue_unicode_data.lua"
    if args.check:
        if target.read_bytes() != expected.encode("utf-8"):
            raise SystemExit("Unicode tables are stale")
    else:
        target.write_bytes(expected.encode("utf-8"))
    print("verified Unicode 15.1 source checksums and generated tables")


if __name__ == "__main__":
    main()
