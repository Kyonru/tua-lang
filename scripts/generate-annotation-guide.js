"use strict";

const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const tags = JSON.parse(fs.readFileSync(path.join(root, "crates/tua-core/resources/annotation-tags.json"), "utf8"));
const text = `<!-- Generated by scripts/generate-annotation-guide.js. -->
# Annotation Guide

Use \`--\` for implementation comments, \`---\` for API prose, and \`---@\`
for Lua-compatible annotations. In native Tua code, prefer types on declarations
and signatures; annotation contracts must agree with native types.

Type \`---@\` to discover tags and hover a complete tag for its meaning.
In VS Code, run **Tua: Open Annotation Guide (Offline)** from the Command Palette.
Tag completion inserts the tag name without replacing your existing arguments.

Recognition does not imply full LuaLS semantics. The descriptions below state
which tags affect checking and which are metadata only. Enable
\`[diagnostics] doc_annotations = true\` in tua.toml to report malformed supported
tags. Use \`-- tua-ignore-next-line CODE\` for Tua diagnostic suppression.

${tags.map(tag => `## @${tag.name}\n\n\`\`\`lua\n${tag.syntax}\n\`\`\`\n\n${tag.description}\n`).join("\n")}`;
for (const relative of ["docs/annotations.md", "editors/vscode/resources/annotation-guide.md"]) {
  const file = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) {
      throw new Error(`${relative} is stale; run node scripts/generate-annotation-guide.js`);
    }
  } else {
    fs.writeFileSync(file, text);
  }
}
