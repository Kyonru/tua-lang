"use strict";

const childProcess = require("child_process");
const fs = require("fs");
const os = require("os");
const path = require("path");
const {
  LspClient,
  completionItems,
  pathToFileURL,
  positionAfter,
  resolveCommand,
} = require("../editors/vscode/scripts/lsp-profile-common");

function generateLargeTableSource(fieldCount, deepTableDepth = 16) {
  if (!Number.isSafeInteger(fieldCount) || fieldCount < 1) {
    throw new Error("fieldCount must be a positive safe integer");
  }
  if (!Number.isSafeInteger(deepTableDepth) || deepTableDepth < 1 || deepTableDepth >= 64) {
    throw new Error("deepTableDepth must be between 1 and 63");
  }

  const width = String(fieldCount - 1).length;
  const fields = new Array(fieldCount);
  const values = new Array(fieldCount);
  for (let index = 0; index < fieldCount; index += 1) {
    const suffix = String(index).padStart(width, "0");

    fields[index] = `  field_${suffix}: number,`;
    values[index] = `  field_${suffix} = ${index},`;
  }

  let deepType = "number";
  let deepValue = "1";
  for (let index = deepTableDepth - 1; index >= 0; index -= 1) {
    const suffix = String(index).padStart(2, "0");

    deepType = `{ level_${suffix}: ${deepType} }`;
    deepValue = `{ level_${suffix} = ${deepValue} }`;
  }

  const body = [
    "-- Generated by scripts/profile-large-tables.js.",
    "type Wide = {",
    ...fields,
    "}",
    `type Deep = ${deepType}`,
    "local wide: Wide = {",
    ...values,
    "}",
    `local deep: Deep = ${deepValue}`,
  ];
  const checked = [
    ...body,
    "return { wide = wide, deep = deep }",
    "",
  ].join("\n");
  const firstField = `field_${String(0).padStart(width, "0")}`;

  return {
    checked,
    editor: [
      ...body,
      `local completion_probe = wide.${firstField}`,
      "return { wide = wide, deep = deep, completion_probe = completion_probe }",
      "",
    ].join("\n"),
    firstField,
    lastField: `field_${String(fieldCount - 1).padStart(width, "0")}`,
  };
}

async function profileFixture(command, fieldCount, deepTableDepth) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), `tua-large-table-${fieldCount}-`));
  const source = generateLargeTableSource(fieldCount, deepTableDepth);
  const sourcePath = path.join(root, "src", "main.tua");
  const uri = pathToFileURL(sourcePath).href;

  try {
    fs.mkdirSync(path.dirname(sourcePath), { recursive: true });
    fs.writeFileSync(path.join(root, "tua.toml"), 'source = "src"\n', "utf8");
    fs.writeFileSync(sourcePath, source.checked, "utf8");

    const compiler = await runMeasuredProcess(command, ["check"], root);
    if (compiler.code !== 0) {
      throw new Error(`tua check failed for ${fieldCount} fields:\n${compiler.stderr}`);
    }

    const client = new LspClient(command, root, { requestTimeoutMs: 120_000 });
    await client.start();
    await client.request("initialize", {
      processId: process.pid,
      rootUri: pathToFileURL(root).href,
      capabilities: {},
      workspaceFolders: [{ uri: pathToFileURL(root).href, name: path.basename(root) }],
    });
    client.notify("initialized", {});
    client.notify("textDocument/didOpen", {
      textDocument: { uri, languageId: "tua", version: 1, text: source.editor },
    });

    const lspStarted = process.hrtime.bigint();
    let lspPeakRssKib = residentSetKib(client.child.pid);
    const sampler = setInterval(() => {
      lspPeakRssKib = maxOptional(lspPeakRssKib, residentSetKib(client.child.pid));
    }, 20);
    let completion;
    try {
      completion = await client.request("textDocument/completion", {
        textDocument: { uri },
        position: positionAfter(source.editor, "wide."),
      });
    } finally {
      clearInterval(sampler);
      lspPeakRssKib = maxOptional(lspPeakRssKib, residentSetKib(client.child.pid));
    }
    const lspElapsedMs = Number(process.hrtime.bigint() - lspStarted) / 1_000_000;
    const labels = completionItems(completion).map((item) => item.label);
    const fieldLabels = labels.filter((label) => label.startsWith("field_"));
    const diagnosticsMessage = await client.waitForDiagnostics(uri, { timeoutMs: 120_000 });
    const diagnostics = diagnosticsMessage.params?.diagnostics;

    await client.request("shutdown", null);
    const done = client.done();
    client.notify("exit", null);
    await done;

    if (!Array.isArray(diagnostics) || diagnostics.length !== 0) {
      throw new Error(
        `editor fixture produced diagnostics for ${fieldCount}-field table: ` +
          JSON.stringify(diagnostics),
      );
    }
    if (
      fieldLabels.length !== fieldCount ||
      new Set(fieldLabels).size !== fieldCount ||
      !fieldLabels.includes(source.firstField) ||
      !fieldLabels.includes(source.lastField)
    ) {
      const uniqueFieldCount = new Set(fieldLabels).size;

      throw new Error(
        `completion returned ${fieldLabels.length} field entries ` +
          `(${uniqueFieldCount} unique) for ${fieldCount}-field table`,
      );
    }

    return {
      fieldCount,
      deepTableDepth,
      sourceBytes: Buffer.byteLength(source.checked),
      compiler: {
        elapsedMs: compiler.elapsedMs,
        peakRssKib: compiler.peakRssKib,
      },
      lspCompletion: {
        elapsedMs: lspElapsedMs,
        peakRssKib: lspPeakRssKib,
        fieldItems: fieldLabels.length,
      },
    };
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

function runMeasuredProcess(command, args, cwd) {
  return new Promise((resolve, reject) => {
    const started = process.hrtime.bigint();
    const child = childProcess.spawn(command, args, {
      cwd,
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
    });
    let stdout = "";
    let stderr = "";
    let peakRssKib = null;
    const sampler = setInterval(() => {
      peakRssKib = maxOptional(peakRssKib, residentSetKib(child.pid));
    }, 20);

    child.stdout.on("data", (chunk) => {
      stdout += chunk.toString("utf8");
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk.toString("utf8");
    });
    child.once("error", reject);
    child.once("exit", (code) => {
      clearInterval(sampler);
      resolve({
        code,
        stdout,
        stderr,
        peakRssKib,
        elapsedMs: Number(process.hrtime.bigint() - started) / 1_000_000,
      });
    });
  });
}

function residentSetKib(pid) {
  if (!pid) {
    return null;
  }
  if (process.platform === "linux") {
    try {
      const status = fs.readFileSync(`/proc/${pid}/status`, "utf8");
      const match = /^VmRSS:\s+(\d+)\s+kB$/m.exec(status);

      return match ? Number(match[1]) : null;
    } catch {
      return null;
    }
  }
  if (process.platform === "darwin") {
    try {
      const output = childProcess.execFileSync("ps", ["-o", "rss=", "-p", String(pid)], {
        encoding: "utf8",
      });
      const value = Number(output.trim());

      return Number.isFinite(value) ? value : null;
    } catch {
      return null;
    }
  }
  return null;
}

function maxOptional(left, right) {
  if (left === null) return right;
  if (right === null) return left;
  return Math.max(left, right);
}

async function main() {
  const command = resolveCommand(process.argv[2] || "target/release/tua");
  const fieldCounts = (process.env.TUA_LARGE_TABLE_FIELDS || "1000,10000")
    .split(",")
    .map((value) => Number(value.trim()));
  const deepTableDepth = Number(process.env.TUA_DEEP_TABLE_DEPTH || "16");
  const outputPath = path.resolve(
    process.env.TUA_LARGE_TABLE_PROFILE_OUT ||
      path.join("target", "tua-speed", "large-table-profile.json"),
  );
  const profiles = [];

  for (const fieldCount of fieldCounts) {
    const profile = await profileFixture(command, fieldCount, deepTableDepth);

    profiles.push(profile);
    console.log(
      `${fieldCount} fields: check ${profile.compiler.elapsedMs.toFixed(1)}ms, ` +
        `completion ${profile.lspCompletion.elapsedMs.toFixed(1)}ms, ` +
        `compiler RSS ${profile.compiler.peakRssKib ?? "unavailable"} KiB, ` +
        `LSP RSS ${profile.lspCompletion.peakRssKib ?? "unavailable"} KiB`,
    );
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(
    outputPath,
    `${JSON.stringify({ generatedAt: new Date().toISOString(), command, profiles }, null, 2)}\n`,
    "utf8",
  );
  console.log(`wrote ${outputPath}`);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error.stack || error.message);
    process.exit(1);
  });
}

module.exports = { generateLargeTableSource, maxOptional };
