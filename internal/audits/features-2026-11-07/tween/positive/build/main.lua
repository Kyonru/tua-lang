local tween = require("tuatween")
local box = { x = 0, y = 10 }
local t = tween.to(box, 1, { x = 10 })
t:ease("linear")
t:onstart(function() print("start") end)
t:onupdate(function() print("update") end)
t:oncomplete(function() print("complete") end)
t:after(1, { y = 0 })
tween.update(0.5)
print(box.x, box.y)
tween.update(0.5)
tween.update(1)
print(box.x, box.y)
local ui = tween.group()
ui:to(box, 0, { x = 20 })
ui:update(0)
print(box.x)
