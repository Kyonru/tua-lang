package.path = 'vendor/runtime/?.lua;' .. package.path
local tween = require('tuatween')
local function probe(name, fn)
 local ok, err = pcall(fn)
 print(name, ok, err or '')
end
probe('existing_suite', function() dofile('vendor/tests/tween_test.lua') end)
probe('takeover', function()
 local g = tween.group(); local b={x=0,y=0}
 g:to(b,2,{x=20,y=20}):ease('linear'); g:update(1)
 g:to(b,1,{x=30}):ease('linear'); g:update(0.5)
 assert(b.x==20 and b.y==15); g:update(0.5); assert(b.x==30 and b.y==20)
end)
probe('callback_accumulation', function()
 local g=tween.group(); local log=''
 g:to({x=0},0,{x=1}):oncomplete(function() log=log..'a' end):oncomplete(function() log=log..'b' end)
 g:update(0); assert(log=='ab')
end)
probe('stop_from_onupdate', function()
 local g=tween.group(); local b={x=0}; local t=g:to(b,1,{x=1})
 t:onupdate(function() t:stop() end); g:update(1)
 print('remaining',#g)
end)
probe('stop_other_from_oncomplete', function()
 local g=tween.group(); local a=g:to({x=0},1,{x=1})
 g:to({x=0},1,{x=1}):oncomplete(function() a:stop() end)
 g:update(1)
end)
probe('stop_from_onstart', function()
 local g=tween.group(); local b={x=0}; local t=g:to(b,1,{x=1})
 t:onstart(function() t:stop() end); g:update(0.5)
 print('cancelled_value',b.x)
 assert(b.x==0,'stop changed target after cancellation')
end)
probe('zero_negative_duration', function()
 for _, duration in ipairs({0,-1}) do
 local g=tween.group(); local b={x=0}; g:to(b,duration,{x=1}); g:update(0); assert(b.x==1)
 end
end)
probe('delay_overshoot', function()
 local g=tween.group(); local b={x=0}; g:to(b,1,{x=1}):delay(0.25); g:update(1); print('after_one_second', b.x)
end)
probe('missing_property_runtime', function()
 local g=tween.group(); g:to({},1,{x=1}); local ok,err=pcall(function() g:update(0.5) end); assert(not ok); print(err)
end)
