function love.load()
 local canvas = love.graphics.newCanvas(32,24)
 canvas:setFilter("nearest")
 local w,h = canvas:getDimensions()
 assert(w == 32 and h == 24)
 local font = love.graphics.newFont(12)
 local text = love.graphics.newText(font,"hello")
 text:set("works")
 assert(text:getWidth() > 0)
 local background = {0.1,0.2,0.3}
 love.graphics.setColor(background)
 love.graphics.draw(canvas,0,0)
 love.graphics.draw(text,0,0)
 local ok, err = pcall(function() text:set("x"):getWidth() end)
 print("LOVE_AUDIT void_chain",ok,err)
 assert(not ok)
 print("LOVE_AUDIT runtime passed", love.getVersion())
 love.event.quit(0)
end
