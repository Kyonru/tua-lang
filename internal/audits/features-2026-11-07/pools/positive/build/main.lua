local __tua_object_pool = require("tuaobjectpool")
local pool = __tua_object_pool({create=function() return {x=0} end,reset=function(b) b.x=0 end,initial=2})
local b = pool:acquire()
b.x = 12
assert(pool:release(b))
assert(not pool:release(b))
assert(not pool:release({x=0}))
assert(pool:acquire()==b)
assert(pool:prewarm(4)==3)
assert(pool:capacity()==5)
pool:clear()
assert(pool:capacity()==0)
print("positive PASS")
