'use strict';
const path = require('node:path');
const assert = require('node:assert/strict');
const {connect, save, binary} = require('../../../devex-2026-11-06/harness');
(async()=>{const s=await connect(__dirname);try{
const doc=s.open('src/main.tua');
await s.query('imported function','textDocument/hover',doc,'board.move(0, 1)',8);
await s.query('imported nested state','textDocument/hover',doc,'board.state.moves',14);
await s.query('LOVE docs','textDocument/hover',doc,'love.graphics.rectangle',17);
await s.query('move arguments','textDocument/signatureHelp',doc,'board.move(0, 1)',13);
await s.query('definition','textDocument/definition',doc,'board.move(0, 1)',8);
await s.query('diagnostics','textDocument/diagnostic',doc);
await s.ask('format','textDocument/formatting',{textDocument:{uri:doc.uri},options:{tabSize:2,insertSpaces:true}});
s.change(doc,doc.text+'\nboard.player.\n');
await s.query('incomplete nested member','textDocument/completion',doc,'board.player.',13,{context:{triggerKind:1}});
const result = label => s.inbound.find(r => r.label === label).result;
assert.match(result('imported function').contents.value, /dx: number, dy: number.*boolean/);
assert.match(result('imported nested state').contents.value, /moves: number/);
assert.match(result('LOVE docs').contents.value, /Draws a rectangle/);
assert.equal(result('move arguments').activeParameter, 1);
assert.ok(result('definition').uri.endsWith('/src/board.tua'));
assert.deepEqual(result('diagnostics').items, []);
assert.deepEqual(result('incomplete nested member').map(i => i.label), ['x', 'y']);
assert.ok(result('format').length > 0);
save(path.join(__dirname,'lsp-evidence.json'),{binary,verified: true,requests:s.inbound});
for(const r of s.inbound) console.log(r.label,JSON.stringify(r.result).slice(0,700));
}finally{await s.close();}})().catch(e=>{console.error(e);process.exitCode=1});
