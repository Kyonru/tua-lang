local root = assert(os.getenv('TUA_PUZZLE_BUILD'))
package.path = root .. '/?.lua;' .. package.path
local board = require('board')
board.reset()
assert(board.move(-1, 0) and board.box.x == 4 and board.state.moves == 1)
assert(board.move(-1, 0) and board.state.won and board.box.x == 3)
assert(not board.move(1, 0) and board.state.moves == 2)
board.reset()
assert(not board.state.won and board.state.moves == 0)
assert(board.move(0, -1))
assert(not board.move(0, -1) and board.state.moves == 1)
board.reset()
assert(board.move(0, 1))
assert(board.move(-1, 0))
assert(board.move(0, -1))
assert(not board.move(0, -1) and board.box.y == 2)
-- Exercise the emitted callbacks with the real graphics subsystem.
dofile(root .. '/main.lua')
love.load()
love.keypressed('left')
love.keypressed('left')
assert(board.state.won)
love.draw()
love.keypressed('r')
assert(not board.state.won and board.player.x == 6)
print('puzzle smoke PASS: push, victory, frozen win, reset, walls, blocked push, emitted callbacks/draw')
love.event.quit(0)
