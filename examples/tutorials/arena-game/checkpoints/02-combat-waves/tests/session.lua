local Session = require("session")
local session = Session.new()
assert(not session.update(1, 1, 0, "none") and session.player.x == 800)
for _ = 1, 100 do
  assert(not session.update(1, 1, 0, "confirm"))
  assert(session.flow:is("playing") and session.player.x == 800)
  assert(session.update(1, 1, 0, "none") and session.player.x == 845)
  assert(not session.update(1, 1, 0, "pause"))
  assert(not session.update(1, 1, 0, "none") and session.player.x == 845)
  assert(not session.update(1, 1, 0, "confirm"))
  session.focus(false)
  assert(session.flow:is("paused"))
  assert(not session.update(1, 1, 0, "confirm"))
  session.focus(true)
  assert(not session.update(1, 1, 0, "none"))
  assert(not session.update(1, 1, 0, "restart"))
  assert(session.player.x == 800 and session.state.time == 0)
  assert(not session.update(1, 1, 0, "leave"))
  assert(session.flow:is("title"))
end
print("ARENA_SESSION_OK title, transitions, pause, focus, 100 restarts")
